export const COHORTS = ['2026', '2025', '2024', '2023', '2022', '更早', '校友', '教职工'];

const LABEL = { 更早: '2021 级及更早' };

/** 年级的显示名；空的返回空字符串 */
export function cohortLabel(c) {
  if (!c) return '';
  return LABEL[c] || (/^\d{4}$/.test(c) ? `${c} 级` : String(c));
}

/** 落款一行："2024 级，计算机学院，阿川"；三项都空是"未落款" */
export function signature(a) {
  const parts = a ? [cohortLabel(a.cohort), a.dept, a.name].filter(Boolean) : [];
  return parts.length ? parts.join('，') : '未落款';
}

